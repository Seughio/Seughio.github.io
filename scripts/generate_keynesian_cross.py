"""Generate the minimal single-panel Keynesian cross (standard library only)."""
from dataclasses import dataclass
from html import escape
from math import atan, degrees, isclose
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'docs/金融学/宏观经济学/figures'
LOW,HIGH=7600,8800
A0,A1,B=1600,1700,.8
Y0,Y1=A0/(1-B),A1/(1-B)
@dataclass(frozen=True)
class Layout:
    width:int
    height:int
    left:int
    top:int
    side:int
    mobile:bool=False
    @property
    def scale(self): return self.side/(HIGH-LOW)
    @property
    def bottom(self): return self.top+self.side
    def x(self,v): return self.left+(v-LOW)*self.scale
    def y(self,v): return self.bottom-(v-LOW)*self.scale
def f(v): return f'{v:.4f}'.rstrip('0').rstrip('.')
def render(c):
    out=[]
    def line(x1,y1,x2,y2,cls,id=''):
        out.append(f'<path class="{cls}" d="M{f(x1)} {f(y1)}L{f(x2)} {f(y2)}"'+(f' id="{id}"' if id else '')+'/>')
    def text(x,y,value,cls='label',anchor='start',transform=''):
        out.append(f'<text x="{f(x)}" y="{f(y)}" class="{cls}" text-anchor="{anchor}"'+(f' transform="{transform}"' if transform else '')+f'>{escape(value)}</text>')
    out.append(f'<svg xmlns="http://www.w3.org/2000/svg" width="{c.width}" height="{c.height}" viewBox="0 0 {c.width} {c.height}" role="img" aria-labelledby="title desc">')
    out.append('<title id="title">自发支出与均衡收入</title>')
    out.append('<desc id="desc">E₀=1600+0.8Y，E₁=1700+0.8Y，均衡线 E=Y。两个均衡点为 (8000,8000)、(8500,8500)。自发支出增加100，均衡收入增加500。横纵轴等比例，展示7600至8800的局部范围。</desc>')
    out.append(f'<!-- Generated by scripts/generate_keynesian_cross.py. X(Y)={c.left}+(Y-{LOW})*{c.scale}; P(E)={c.bottom}-(E-{LOW})*{c.scale}. -->')
    out.append(f'<metadata id="mapping">{{"domain":[{LOW},{HIGH}],"left":{c.left},"top":{c.top},"bottom":{c.bottom},"scale":{c.scale},"deltaA":100,"deltaY":500,"multiplier":5}}</metadata>')
    out.append('''<style>
    :root {
      --paper:#fff; --ink:#46564c; --muted:#78847c;
      --green:#416f5d; --ochre:#ad7c51; --ochre-text:#96643e;
      --axis:#939f97; --guide:#dfe5e0; --equilibrium:#c0c8c1;
      --curve-width:1.8; --axis-width:.85; --guide-width:.75;
      --title-size:14px; --label-size:15px; --tick-size:12.5px; --measure-size:14px;
    }
    text {font-family:'Microsoft YaHei','PingFang SC','Noto Sans CJK SC',sans-serif;font-variant-numeric:tabular-nums;fill:var(--ink);font-weight:400;}
    path {fill:none;stroke-linecap:butt;}
    .heading {font-size:var(--title-size);font-weight:500;}
    .label {font-size:var(--label-size);}
    .tick {font-size:var(--tick-size);fill:var(--muted);}
    .measure {font-size:var(--measure-size);}
    .axis {stroke:var(--axis);stroke-width:var(--axis-width);}
    .guide {stroke:var(--guide);stroke-width:var(--guide-width);stroke-dasharray:3 5;}
    .eq {stroke:var(--equilibrium);stroke-width:1.1;}
    .old {stroke:var(--green);stroke-width:var(--curve-width);}
    .new {stroke:var(--ochre);stroke-width:var(--curve-width);}
    .old-label {fill:var(--green);}
    .new-label {fill:var(--ochre-text);}
    .eq-label {fill:var(--muted);}
    .old-point {fill:var(--green);stroke:white;stroke-width:1.1;}
    .new-point {fill:var(--ochre);stroke:white;stroke-width:1.1;}
    .dimension {stroke:var(--ink);stroke-width:1;}
    </style>''')
    if c.mobile: out.append('<style>:root {--measure-size:12px;--title-size:13px;}</style>')
    out.append(f'<rect width="{c.width}" height="{c.height}" fill="var(--paper)"/>')
    text(c.left,23 if c.mobile else 27,'自发支出与均衡收入','heading')
    for income in [Y0,Y1]:
        px,py=c.x(income),c.y(income)
        line(c.left,py,px,py,'guide');line(px,py,px,c.bottom,'guide')
    line(c.left,c.top,c.left,c.bottom,'axis')
    line(c.left,c.bottom,c.left+c.side+10,c.bottom,'axis')
    for income in [LOW,Y0,Y1]:
        text(c.left-12,c.y(income)+4,str(round(income)),'tick','end')
        text(c.x(income),c.bottom+23,str(round(income)),'tick','middle')
    text(c.left-19,c.top+5,'E','label','end')
    text(c.left+c.side+21,c.bottom+5,'Y')
    for a,b,cls,id,name in [(0,1,'eq','equilibrium-line','E = Y'),(A0,B,'old','old-expenditure','E₀'),(A1,B,'new','new-expenditure','E₁')]:
        lo=max(LOW,(LOW-a)/b);hi=min(HIGH,(HIGH-a)/b)
        ex,ey=c.x(hi),c.y(a+b*hi)
        line(c.x(lo),c.y(a+b*lo),ex,ey,cls,id)
        if cls=='eq': text(ex-8,ey-13,name,'label eq-label','end')
        else: text(ex+12,ey+5,name,f'label {cls}-label')
    for income,cls in [(Y0,'old-point'),(Y1,'new-point')]:
        out.append(f'<circle cx="{f(c.x(income))}" cy="{f(c.y(income))}" r="3.6" class="{cls}"/>')
    # Fixed-income vertical dimension: exactly 100*scale pixels.
    at=7640 if c.mobile else 7700
    dx=c.x(at);upper,lower=c.y(A1+B*at),c.y(A0+B*at)
    line(dx,upper,dx,lower,'dimension','delta-a')
    for yy in [upper,lower]: line(dx-3,yy,dx+3,yy,'dimension')
    # Place the label on the midline of the channel, parallel to the curves.
    label_income=7790 if c.mobile else 7820
    lx=c.x(label_income);ly=c.y((A0+A1)/2+B*label_income)
    text(lx,ly+4,'ΔA = +100','measure','middle',f'rotate({f(-degrees(atan(B)))} {f(lx)} {f(ly)})')
    yy=c.bottom+46
    for income in [Y0,Y1]:
        xx=c.x(income);line(xx,c.bottom+30,xx,yy+4,'guide');line(xx,yy-3,xx,yy+3,'dimension')
    line(c.x(Y0),yy,c.x(Y1),yy,'dimension','delta-y')
    text((c.x(Y0)+c.x(Y1))/2,yy+26,'ΔY = +500','measure','middle')
    assert isclose((lower-upper)/c.scale,100)
    assert isclose((c.x(Y1)-c.x(Y0))/(lower-upper),5)
    assert isclose(c.x(Y1)-c.x(Y0),c.y(Y0)-c.y(Y1))
    out.append('</svg>')
    return '\n'.join(out)+'\n'
if __name__=='__main__':
    for name,c in [('ch02-keynesian-cross.svg',Layout(600,590,64,60,440)),('ch02-keynesian-cross-mobile.svg',Layout(400,428,50,54,280,True))]:
        (OUT/name).write_text(render(c),encoding='utf-8');print(f'{name}: {c.scale:g} px/unit on both axes')
